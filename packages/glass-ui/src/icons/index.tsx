const registry = new Map<string, ReactNode | LucideComponent>();

/** Rejestruje własną ikonę (np. z features/*). Komponent lub węzeł SVG 24×24 rysowany `currentColor`. */
export function registerIcon(name: string, icon: ReactNode | LucideComponent): void {
  registry.set(name, icon);
}

export type VehicleIconName = CustomIconName;
export type IconName = keyof typeof LUCIDE | VehicleIconName;
export const ICON_NAMES: readonly string[] = [...Object.keys(LUCIDE), ...Object.keys(CUSTOM_ICONS)];

export interface IconGlyphProps extends Omit<SVGProps<SVGSVGElement>, "name" | "ref"> {
  name: string;
  size?: number;
  strokeWidth?: number;
}

const warned = new Set<string>();

/** Sam glif SVG (bez opakowania). */
export function IconGlyph({ name, size = 24, strokeWidth = 2, ...rest }: IconGlyphProps) {
  const custom = CUSTOM_ICONS[name as CustomIconName];
  const reg = registry.get(name);
  const Lucide = LUCIDE[name];
  const common = {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
    focusable: false,
    ...rest,
  };
  if (reg !== undefined && typeof reg !== "function") return <svg {...common}>{reg}</svg>;
  if (typeof reg === "function") {
    const C = reg as LucideComponent;
    return <C size={size} strokeWidth={strokeWidth} {...(rest as LucideProps)} />;
  }
  if (custom) return <svg {...common}>{custom.body}</svg>;
  if (Lucide) {
    const C = Lucide;
    return <C size={size} strokeWidth={strokeWidth} aria-hidden {...(rest as LucideProps)} />;
  }
  if (!warned.has(name)) {
    warned.add(name);
    console.warn(`[glass-ui] Icon: nieznana nazwa "${name}" (lista: ICON_NAMES)`);
  }
  return <CircleHelp size={size} strokeWidth={strokeWidth} aria-hidden {...(rest as LucideProps)} />;
}
