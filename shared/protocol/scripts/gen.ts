/**
 * Generuje artefakty z kontraktu:
 *  - shared/protocol/generated/actions.json
 *  - plugin/generated/actions.gen.h   (wejścia urządzeń semantical / generic)
 *  - plugin/generated/channels.gen.h  (kanały do rejestracji)
 * Uruchom: npm run gen -w @yoga-auto/protocol
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ACTIONS, PRESS_FRAMES, HOLD_WATCHDOG_MS } from "../src/actions.ts";
import { PLUGIN_CHANNELS, IPC_HEARTBEAT_MS, IPC_MAX_FRAME_BYTES } from "../src/ipc.ts";
import { IPC_VERSION, PIPE_NAME, PROTOCOL_VERSION, PROTOCOL_MINOR } from "../src/version.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const out = (p: string, s: string) => {
  const f = resolve(root, p);
  mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, s.replace(/\r\n/g, "\n"));
  console.log("gen:", p);
};

const header = `// AUTO-GENERATED by shared/protocol/scripts/gen.ts — DO NOT EDIT.\n// Protocol v${PROTOCOL_VERSION}.${PROTOCOL_MINOR}, IPC v${IPC_VERSION}\n#pragma once\n`;

out("shared/protocol/generated/actions.json", JSON.stringify(ACTIONS, null, 2) + "\n");

const inputs = { semantical: new Set<string>(), generic: new Set<string>() };
for (const a of Object.values(ACTIONS)) {
  if ((a.device as string) === "keyboard") continue;
  for (const n of ([] as string[]).concat(a.scs as string | string[])) inputs[a.device].add(n);
}
const list = (s: Set<string>) =>
  [...s]
    .sort()
    .map((n) => `    "${n}",`)
    .join("\n");
out(
  "plugin/generated/actions.gen.h",
  `${header}
namespace yoga::gen {

constexpr int kIpcVersion = ${IPC_VERSION};
constexpr const wchar_t* kPipeName = L"${PIPE_NAME.split(String.fromCharCode(92)).join(String.fromCharCode(92, 92))}";
constexpr unsigned kPressFrames = ${PRESS_FRAMES};
constexpr unsigned kHoldWatchdogMs = ${HOLD_WATCHDOG_MS};
constexpr unsigned kHeartbeatMs = ${IPC_HEARTBEAT_MS};
constexpr unsigned kMaxFrameBytes = ${IPC_MAX_FRAME_BYTES};

// Wejścia urządzenia SCS_INPUT_DEVICE_TYPE_semantical (nazwa = mix z controls.sii)
constexpr const char* kSemanticalInputs[] = {
${list(inputs.semantical) || '    "",'}
};
constexpr unsigned kSemanticalInputCount = ${inputs.semantical.size};

// Wejścia urządzenia SCS_INPUT_DEVICE_TYPE_generic
constexpr const char* kGenericInputs[] = {
${list(inputs.generic) || '    "",'}
};
constexpr unsigned kGenericInputCount = ${inputs.generic.size};

} // namespace yoga::gen
`,
);

const typeMap: Record<string, string> = {
  float: "SCS_VALUE_TYPE_float",
  double: "SCS_VALUE_TYPE_double",
  bool: "SCS_VALUE_TYPE_bool",
  u32: "SCS_VALUE_TYPE_u32",
  s32: "SCS_VALUE_TYPE_s32",
  u64: "SCS_VALUE_TYPE_u64",
  dplacement: "SCS_VALUE_TYPE_dplacement",
  fvector: "SCS_VALUE_TYPE_fvector",
};
out(
  "plugin/generated/channels.gen.h",
  `${header}#include <scssdk_value.h>

namespace yoga::gen {

struct ChannelDef {
    const char* name;      // nazwa SDK; "{i}" zastępowane indeksem przyczepy
    scs_value_type_t type;
    unsigned indexCount;   // 0 = kanał nieindeksowany
    bool fast;
};

constexpr ChannelDef kChannels[] = {
${PLUGIN_CHANNELS.map((c) => `    { "${c.name}", ${typeMap[c.type]}, ${c.idx ?? 0}u, ${c.fast ? "true" : "false"} },`).join("\n")}
};
constexpr unsigned kChannelCount = ${PLUGIN_CHANNELS.length};

} // namespace yoga::gen
`,
);
